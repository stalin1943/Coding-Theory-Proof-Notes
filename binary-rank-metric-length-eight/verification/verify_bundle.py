#!/usr/bin/env python3
"""Check the delivered evidence, or regenerate the entire proof computation.

Default: integrity, complete case-count comparison, and every final rank-support
obstruction. --recompute additionally regenerates both catalogues and all 20-bit
normal-form enumerations. Python standard library and C++17 only.
"""
import argparse
import concurrent.futures
import csv
import gzip
import hashlib
import io
import json
import os
import shutil
import subprocess
import tempfile
from pathlib import Path

from verify_witnesses import verify as verify_witnesses
from verify_projection_types import check as check_projection_types

ROOT = Path(__file__).resolve().parent
FIELDS = ['orbit', 'k', 'core_heavy', 'normal_forms', 'after_rank34',
          'after_rank2', 'point_bad', 'hyperplane_bad', 'two_span', 'target']
TOTALS = dict(normal_forms=10519314432, after_rank34=34116,
              after_rank2=12160, point_bad=0, hyperplane_bad=0,
              two_span=12160, target=0)


def compressed_text(name: str) -> str:
    with gzip.open(ROOT / 'data' / (name + '.gz'), 'rt', encoding='utf-8') as f:
        return f.read()


def read_csv_text(text: str) -> list[dict[str, str]]:
    return list(csv.DictReader(io.StringIO(text)))


def table_check(primary, independent):
    assert len(primary) == len(independent) == 10032
    assert primary == independent, 'Primary and independent complete tables differ.'
    assert [(int(r['orbit']), int(r['k'])) for r in primary] == [
        (i, j) for i in range(912) for j in range(11)]
    assert all(int(r['normal_forms']) == 1048576 for r in primary)
    for k, value in TOTALS.items():
        assert sum(int(r[k]) for r in primary) == value, k


def integrity_check():
    manifest = ROOT / 'SHA256SUMS'
    if not manifest.exists():
        raise FileNotFoundError('Missing SHA256SUMS')
    checked = 0
    for line in manifest.read_text().splitlines():
        if not line.strip():
            continue
        digest, name = line.split('  ', 1)
        p = ROOT / name
        assert p.is_file(), name
        assert hashlib.sha256(p.read_bytes()).hexdigest() == digest, name
        checked += 1
    print(f'Integrity: {checked} files passed.')


def check_catalogue_data():
    cat = read_csv_text(compressed_text('plane4_catalog.csv'))
    cover = read_csv_text(compressed_text('plane4_cover.csv'))
    assert len(cat) == 912 and len(cover) == 173786
    assert [int(r['orbit']) for r in cat] == list(range(912))
    assert sum(int(r['normalized_members']) for r in cat) == 173786
    keys = [(int(r['a']), int(r['b'])) for r in cover]
    assert len(set(keys)) == 173786
    members = [0] * 912
    for r in cover:
        o, a, b = int(r['orbit']), int(r['a']), int(r['b'])
        assert 0 <= o < 912 and 0 < a < b < (a ^ b) < 1024
        members[o] += 1
    assert members == [int(r['normalized_members']) for r in cat]
    print('Catalogue data: 912 classes, 173786 disjoint normalized records.')
    print('Completeness of the group action is regenerated by --recompute.')


def check_witness_files(primary: Path, independent: Path):
    a = verify_witnesses(primary, 91, False)
    b = verify_witnesses(independent, 67, True)
    assert a['verified'] == b['verified'] == 12160
    assert a['heavy_point_histogram'] == b['heavy_point_histogram'] == {
        0: 939, 1: 360, 2: 49, 3: 12, 5: 10800}
    print('Final obstructions: 12160 per field; all ranks (4,4,8).')
    return a, b


def basic_checks():
    integrity_check()
    check_catalogue_data()
    projection_result = check_projection_types()
    assert projection_result['covered_four_spaces'] == 651
    print('Projection classes: all 651 four-dimensional subspaces covered exactly.')
    a = read_csv_text(compressed_text('general_counts_primary.csv'))
    b = read_csv_text(compressed_text('general_counts_independent.csv'))
    table_check(a, b)
    print('All 10032 case-count rows agree exactly.')
    with tempfile.TemporaryDirectory(prefix='8432_witness_') as tmp:
        p = Path(tmp) / 'primary.txt'
        q = Path(tmp) / 'independent.txt'
        p.write_text(compressed_text('general_survivors_primary.txt'))
        q.write_text(compressed_text('general_survivors_independent.txt'))
        check_witness_files(p, q)


def run_logged(command, directory: Path, log: str):
    with (directory / log).open('w') as f:
        subprocess.run(command, cwd=directory, stdout=f,
                       stderr=subprocess.STDOUT, check=True)


def regenerate(work: Path, compiler: str, workers: int):
    if work.exists() and any(work.iterdir()):
        raise ValueError(f'Recomputation directory must be empty: {work}')
    work.mkdir(parents=True, exist_ok=True)
    if not shutil.which(compiler):
        raise FileNotFoundError(f'C++ compiler not found: {compiler}')
    exe_suffix = '.exe' if os.name == 'nt' else ''
    binaries = {}
    for name in ['classify_plane4', 'general_plane_graph', 'independent_complete']:
        exe = work / (name + exe_suffix)
        subprocess.run([compiler, '-O3', '-std=c++17',
                        str(ROOT / 'src' / (name + '.cpp')), '-o', str(exe)], check=True)
        binaries[name] = str(exe.resolve())
    run_logged([binaries['classify_plane4']], work, 'classify.log')
    assert (work / 'plane4_catalog.csv').read_text() == compressed_text('plane4_catalog.csv')
    assert (work / 'plane4_cover.csv').read_text() == compressed_text('plane4_cover.csv')
    print('Primary catalogue regenerated exactly.')

    workers = max(1, min(workers, 912))
    ranges = [(i * 912 // workers, (i + 1) * 912 // workers - 1)
              for i in range(workers)]
    for family in ['primary', 'independent']:
        name = 'general_plane_graph' if family == 'primary' else 'independent_complete'
        with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as pool:
            tasks = []
            for lo, hi in ranges:
                command = [binaries[name], str(lo), str(hi)]
                if family == 'primary':
                    command += ['91']
                tasks.append(pool.submit(run_logged, command, work,
                                         f'{family}_{lo}_{hi}.log'))
            for task in tasks:
                task.result()
        print(f'{family.capitalize()} full enumeration completed.')

    p_rows, i_rows, p_text, i_text = [], [], [], []
    catalogue = read_csv_text(compressed_text('plane4_catalog.csv'))
    for lo, hi in ranges:
        p_rows += read_csv_text((work / f'general_counts_{lo}_{hi}_91.csv').read_text())
        i_rows += read_csv_text((work / f'ind_counts_{lo}_{hi}.csv').read_text())
        p_text.append((work / f'general_survivors_{lo}_{hi}_91.txt').read_text())
        i_text.append((work / f'ind_survivors_{lo}_{hi}.txt').read_text())
        independent_cat = read_csv_text((work / f'ind_catalog_{lo}_{hi}.csv').read_text())
        assert len(independent_cat) == 912
        for a, b in zip(catalogue, independent_cat):
            assert all(a[k] == v for k, v in b.items()), (a, b)
    table_check(p_rows, i_rows)
    assert p_rows == read_csv_text(compressed_text('general_counts_primary.csv'))
    assert i_rows == read_csv_text(compressed_text('general_counts_independent.csv'))
    primary = work / 'recomputed_primary_witnesses.txt'
    independent = work / 'recomputed_independent_witnesses.txt'
    primary.write_text(''.join(p_text))
    independent.write_text(''.join(i_text))
    assert primary.read_text() == compressed_text('general_survivors_primary.txt')
    assert independent.read_text() == compressed_text('general_survivors_independent.txt')
    results = check_witness_files(primary, independent)
    (work / 'verification_result.json').write_text(json.dumps({
        'all_catalogue_rows_match': True, 'all_10032_cases_match': True,
        'all_final_obstructions_match': True, 'totals': TOTALS,
        'witness_verifications': results}, ensure_ascii=False, indent=2) + '\n')
    print('FULL RECOMPUTATION PASSED: no surviving normal form.')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--recompute', action='store_true')
    parser.add_argument('--work', type=Path)
    parser.add_argument('--workers', type=int, default=min(os.cpu_count() or 1, 4))
    parser.add_argument('--compiler', default='g++')
    args = parser.parse_args()
    if not __debug__:
        raise RuntimeError('Do not use python -O; assertions are exact proof checks.')
    basic_checks()
    if args.recompute:
        if args.work:
            regenerate(args.work.resolve(), args.compiler, args.workers)
        else:
            with tempfile.TemporaryDirectory(prefix='8432_recompute_') as tmp:
                regenerate(Path(tmp), args.compiler, args.workers)
    else:
        print('Delivered data checks passed. --recompute regenerates the full cover.')

if __name__ == '__main__':
    main()
